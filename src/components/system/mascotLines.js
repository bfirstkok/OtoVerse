// Each category cycles through a shuffled bag, avoiding repeats at its boundary.
export function createLinePicker(random = Math.random) {
  const bags = new Map();
  const previous = new Map();
  return category => {
    const lines = mascotLines[category] || mascotLines.idle;
    let bag = bags.get(category);
    if (!bag?.length) {
      bag = [...lines];
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
      if (bag.length > 1 && bag[bag.length - 1] === previous.get(category)) {
        [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
      }
      bags.set(category, bag);
    }
    const line = bag.pop();
    previous.set(category, line);
    return line;
  };
}
